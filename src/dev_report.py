"""Write results/v2/development/report.md from the development experiment outputs.

Run: python -m src.dev_report   (after python -m src.experiments)
"""
from pathlib import Path
import json

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "results" / "v2" / "development"


def tbl(name, digits=2):
    return pd.read_csv(D / name).round(digits).to_markdown(index=False)


def main():
    s = json.loads((D / "summary.json").read_text())
    pm = pd.DataFrame({k: s[k] for k in ("pooled_mae_tuning_folds", "pooled_mae_confirmation_folds",
                                         "pooled_mae_all_folds")}).round(3)
    pm.columns = ["tuning WY2008-2015", "confirmation WY2016-2023", "all WY2008-2023"]
    lines = ["# v2 development evaluation (rolling origin, pre-2024 data only)", "",
             "Generated by `python -m src.experiments` and `python -m src.dev_report`. Every number here uses only "
             "observations whose origin and 30-day target are before 2024-01-01. MAE is in percentage points (pp) "
             "of the capacity in force at the forecast origin.", "",
             "Design: expanding window by California water year (Oct 1 to Sep 30). For fold W the models and all "
             "baselines are fit on rows whose targets are observed before Oct 1 of W-1, then evaluated on origins "
             "inside W. HGB hyper-parameters were chosen per variant on the tuning folds only; the confirmation "
             "folds were not used for hyper-parameters.", "",
             f"Rows: {s['n_rows']}.", "",
             "## Pooled MAE by model", "", pm.to_markdown(), "",
             f"Primary model by the predetermined rule (lowest confirmation MAE among HGB variants): "
             f"**{s['primary_model']}** (feature set `{s['primary_feature_set']}`). Strongest baseline: "
             f"**{s['strongest_baseline']}**. Selected HGB hyper-parameters (all variants): "
             f"`{json.dumps(s['all_hgb_hyperparameters'][s['primary_model']])}`; this is the low learning-rate, "
             "low-iteration corner of the predetermined grid.", "",
             "## Water years where each model beats the strongest baseline", "",
             pd.DataFrame(s["wins_by_water_year_vs_strongest_baseline"]).T.to_markdown(), "",
             "## Environmental data ablations: MAE difference (A minus B), moving-block bootstrap 95% CI", "",
             "Negative means A is better. Blocks are consecutive weekly origin dates with all reservoirs resampled "
             "together; 2,000 replicates.", "",
             "| comparison | scope | block | estimate | 95% CI | share A better |", "|---|---|---|---|---|---|"]
    for label, scopes in s["ablations_mae_difference"].items():
        for scope, blocks in scopes.items():
            for b, r in blocks.items():
                lines.append(f"| {label} | {scope} | {b.replace('_', ' ')} | {r['estimate']:.3f} | "
                             f"[{r['ci95_low']:.3f}, {r['ci95_high']:.3f}] | {r['share_better']:.3f} |")
    lines += ["", "## MAE by water year (all folds)", "", tbl("mae_by_wy_all_folds.csv"), "",
              "## MAE by water year class (DWR Sacramento or San Joaquin Valley index; descriptive)", "",
              "All folds:", "", tbl("mae_by_wy_class_all_folds.csv"), "", "Confirmation folds:", "",
              tbl("mae_by_wy_class_confirmation.csv"), "",
              "## MAE by reservoir (confirmation folds)", "", tbl("mae_by_station_id_confirmation.csv"), "",
              "## MAE by origin season (confirmation folds)", "", tbl("mae_by_season_confirmation.csv"), "",
              "## Prediction interval methods (primary model, folds WY2012-2023, calibrated on earlier folds only)", "",
              tbl("interval_methods.csv", 3), "",
              f"Selected by the predetermined rule (narrowest with pooled coverage in [0.87, 0.93]): **{s['interval_method']}**.",
              "", "Coverage and width of the selected method by group:", "",
              pd.read_csv(D / "interval_methods_by_group.csv").query("method == @s['interval_method'] and group_type != 'wy'")
              .round(3).to_markdown(index=False), "",
              "Conformal-style residual quantiles assume exchangeable errors. Errors here are serially correlated and "
              "the climate is non-stationary, so nominal 90% coverage is not guaranteed for future periods.", ""]
    (D / "report.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {D / 'report.md'}")


if __name__ == "__main__":
    main()
